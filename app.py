
from flask import Flask, render_template, request, redirect, url_for, send_file
import sqlite3
import os

app = Flask(__name__)

# Jika DATABASE_URL tersedia, gunakan PostgreSQL (Neon).
# Jika tidak, gunakan SQLite untuk menjalankan proyek di laptop.
DATABASE_URL = os.environ.get("DATABASE_URL")

if DATABASE_URL:
    import psycopg
    from psycopg.rows import dict_row


def get_db():
    if DATABASE_URL:
        return psycopg.connect(
            DATABASE_URL,
            row_factory=dict_row
        )

    database = os.path.join(
        os.path.dirname(os.path.abspath(__file__)),
        "database.db"
    )

    conn = sqlite3.connect(database)
    conn.row_factory = sqlite3.Row
    return conn


def execute(conn, query, params=()):
    # PostgreSQL menggunakan %s, sedangkan SQLite menggunakan ?
    if DATABASE_URL:
        query = query.replace("?", "%s")

    return conn.execute(query, params)


def init_db():
    conn = get_db()

    if DATABASE_URL:
        execute(conn, """
            CREATE TABLE IF NOT EXISTS anggota (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nama TEXT NOT NULL,
                nis TEXT NOT NULL,
                kelas TEXT NOT NULL,
                jenis_kelamin TEXT NOT NULL,
                ekstrakurikuler TEXT NOT NULL,
                kategori TEXT NOT NULL,
                no_hp TEXT
            )
        """)
    else:
        execute(conn, """
            CREATE TABLE IF NOT EXISTS anggota (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                nama TEXT NOT NULL,
                nis TEXT NOT NULL,
                kelas TEXT NOT NULL,
                jenis_kelamin TEXT NOT NULL,
                ekstrakurikuler TEXT NOT NULL,
                kategori TEXT NOT NULL,
                no_hp TEXT
            )
        """)

    conn.commit()
    conn.close()


@app.route("/")
def index():
    db = get_db()

    anggota = execute(
        db,
        "SELECT * FROM anggota ORDER BY id DESC"
    ).fetchall()

    total = len(anggota)

    jumlah_ekskul = execute(
        db,
        """
        SELECT COUNT(DISTINCT ekstrakurikuler) AS jumlah
        FROM anggota
        """
    ).fetchone()["jumlah"]

    data_ekskul = execute(db, """
        SELECT ekstrakurikuler, COUNT(*) AS jumlah
        FROM anggota
        GROUP BY ekstrakurikuler
        ORDER BY jumlah DESC
    """).fetchall()

    jumlah_per_ekskul = {
        row["ekstrakurikuler"]: row["jumlah"]
        for row in data_ekskul
    }

    db.close()

    return render_template(
        "index.html",
        anggota=anggota,
        total=total,
        jumlah_ekskul=jumlah_ekskul,
        jumlah_per_ekskul=jumlah_per_ekskul
    )


@app.route("/tambah", methods=["GET", "POST"])
def tambah():
    if request.method == "POST":
        nama = request.form["nama"]
        nis = request.form["nis"]
        kelas = request.form["kelas"]
        jenis_kelamin = request.form["jenis_kelamin"]
        ekstrakurikuler = request.form["ekstrakurikuler"]
        kategori = request.form["kategori"]
        no_hp = request.form["no_hp"]

        conn = get_db()

        execute(conn, """
            INSERT INTO anggota
            (nama, nis, kelas, jenis_kelamin,
             ekstrakurikuler, kategori, no_hp)
            VALUES (?, ?, ?, ?, ?, ?, ?)
        """, (
            nama,
            nis,
            kelas,
            jenis_kelamin,
            ekstrakurikuler,
            kategori,
            no_hp
        ))

        conn.commit()
        conn.close()

        return redirect(url_for("index"))

    return render_template("tambah.html")


@app.route("/edit/<int:id>", methods=["GET", "POST"])
def edit(id):
    conn = get_db()

    data = execute(
        conn,
        "SELECT * FROM anggota WHERE id = ?",
        (id,)
    ).fetchone()

    if not data:
        conn.close()
        return "Data tidak ditemukan", 404

    if request.method == "POST":
        nama = request.form["nama"]
        nis = request.form["nis"]
        kelas = request.form["kelas"]
        jenis_kelamin = request.form["jenis_kelamin"]
        ekstrakurikuler = request.form["ekstrakurikuler"]
        kategori = request.form["kategori"]
        no_hp = request.form["no_hp"]

        execute(conn, """
            UPDATE anggota SET
                nama = ?,
                nis = ?,
                kelas = ?,
                jenis_kelamin = ?,
                ekstrakurikuler = ?,
                kategori = ?,
                no_hp = ?
            WHERE id = ?
        """, (
            nama,
            nis,
            kelas,
            jenis_kelamin,
            ekstrakurikuler,
            kategori,
            no_hp,
            id
        ))

        conn.commit()
        conn.close()

        return redirect(url_for("index"))

    conn.close()

    return render_template("edit.html", data=data)


@app.route("/hapus/<int:id>")
def hapus(id):
    conn = get_db()

    execute(
        conn,
        "DELETE FROM anggota WHERE id = ?",
        (id,)
    )

    conn.commit()
    conn.close()

    return redirect(url_for("index"))


